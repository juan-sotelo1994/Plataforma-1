"""Pasa los datos de las bases SQLite a PostgreSQL (una sola vez).

- Esquema "central": sedes, administradores de sede y la credencial del superadministrador.
- Esquema "sede_<id>" por cada sede: todas las tablas de la sede, con sus datos.

Las bases SQLite no se modifican ni se borran: quedan como respaldo.
Uso (desde la carpeta app, con DATABASE_URL en .env):
    python migrar_a_postgres.py
"""
import os
import re
import sqlite3

import psycopg
from dotenv import load_dotenv
from psycopg import sql

load_dotenv()

APP = os.path.dirname(os.path.abspath(__file__))
INSTANCIA = os.path.join(APP, 'instance')
CENTRAL = os.path.join(INSTANCIA, 'central.db')
# La base de la sede principal tiene todas las tablas, incluidas las que se crean "al vuelo"
BASE_MODELO = os.path.join(INSTANCIA, 'plataforma.db')


def traducir(ddl):
    """Convierte el CREATE TABLE de SQLite a PostgreSQL."""
    ddl = re.sub(r'INTEGER\s+PRIMARY KEY AUTOINCREMENT', 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
                 ddl, flags=re.IGNORECASE)
    if 'CREATE TABLE aspirantes' in ddl:
        ddl = ddl.replace('estudiante_id TEXT', 'estudiante_id INTEGER')
    ddl = ddl.replace("datetime('now', 'localtime')", "to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS')")
    return re.sub(r'\bREAL\b', 'DOUBLE PRECISION', ddl)


def tablas_en_orden(sqlite_conn):
    """Nombres de las tablas, padres antes que hijos (según las llaves foráneas)."""
    tablas = {fila[0]: fila[1] for fila in sqlite_conn.execute(
        "SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'")}
    dependencias = {}
    for nombre in tablas:
        padres = {fk[2] for fk in sqlite_conn.execute(f'PRAGMA foreign_key_list("{nombre}")')}
        dependencias[nombre] = {p for p in padres if p in tablas and p != nombre}
    orden, hechas = [], set()
    while len(orden) < len(tablas):
        listas = [t for t in sorted(tablas) if t not in hechas and dependencias[t] <= hechas]
        if not listas:
            raise RuntimeError(f'Ciclo de llaves foráneas entre: {sorted(set(tablas) - hechas)}')
        orden += listas
        hechas.update(listas)
    return [(t, tablas[t]) for t in orden]


def columnas(sqlite_conn, tabla):
    return [fila[1] for fila in sqlite_conn.execute(f'PRAGMA table_info("{tabla}")')]


def crear_esquema(pg, esquema, definiciones):
    pg.execute(sql.SQL('DROP SCHEMA IF EXISTS {} CASCADE').format(sql.Identifier(esquema)))
    pg.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(esquema)))
    pg.execute(sql.SQL('SET search_path TO {}').format(sql.Identifier(esquema)))
    for _, ddl in definiciones:
        pg.execute(traducir(ddl))


def copiar_datos(pg, esquema, origen, orden):
    for tabla, _ in orden:
        filas = origen.execute(f'SELECT * FROM "{tabla}"').fetchall()
        cols = columnas(origen, tabla)
        if not filas:
            continue
        consulta = sql.SQL('INSERT INTO {}.{} ({}) VALUES ({})').format(
            sql.Identifier(esquema), sql.Identifier(tabla),
            sql.SQL(', ').join(sql.Identifier(c) for c in cols),
            sql.SQL(', ').join(sql.Placeholder() for _ in cols))
        with pg.cursor() as cursor:
            cursor.executemany(consulta, [tuple(fila) for fila in filas])
        if 'id' in cols:
            pg.execute(sql.SQL(
                "SELECT setval(pg_get_serial_sequence({}, 'id'), (SELECT MAX(id) FROM {}.{}))").format(
                sql.Literal(f'{esquema}.{tabla}'), sql.Identifier(esquema), sql.Identifier(tabla)))


def contar(pg, esquema, tabla):
    return pg.execute(sql.SQL('SELECT COUNT(*) FROM {}.{}').format(
        sql.Identifier(esquema), sql.Identifier(tabla))).fetchone()[0]


def main():
    url = os.environ.get('DATABASE_URL')
    if not url:
        raise SystemExit('Falta DATABASE_URL en app/.env')

    central = sqlite3.connect(CENTRAL)
    modelo = sqlite3.connect(BASE_MODELO)
    sedes = central.execute('SELECT id, nombre, archivo FROM sedes ORDER BY id').fetchall()
    orden_central = tablas_en_orden(central)
    orden_sede = tablas_en_orden(modelo)

    with psycopg.connect(url, autocommit=False) as pg:
        # Esquema central
        crear_esquema(pg, 'central', orden_central)
        copiar_datos(pg, 'central', central, orden_central)
        pg.commit()
        print('central:', {t: contar(pg, 'central', t) for t, _ in orden_central})

        # Un esquema por sede
        for sede_id, nombre, archivo in sedes:
            esquema = f'sede_{sede_id}'
            origen = sqlite3.connect(os.path.join(INSTANCIA, archivo))
            crear_esquema(pg, esquema, orden_sede)
            # Solo se copian las tablas que existen en la base de origen
            presentes = {fila[0] for fila in origen.execute(
                "SELECT name FROM sqlite_master WHERE type = 'table'")}
            copiar_datos(pg, esquema, origen, [(t, d) for t, d in orden_sede if t in presentes])
            pg.commit()
            origen.close()
            print(f'{esquema} ({nombre}):',
                  {t: contar(pg, esquema, t) for t, _ in orden_sede if t in presentes})

    central.close()
    modelo.close()
    print('Listo. Las bases SQLite no se modificaron.')


if __name__ == '__main__':
    main()
