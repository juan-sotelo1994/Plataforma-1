-- Generado a partir de la base SQLite de la sede principal. Cada sentencia crea una tabla.
CREATE TABLE credencial_superadmin (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    contrasena_hash TEXT NOT NULL
);

CREATE TABLE sedes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE,
    archivo TEXT NOT NULL UNIQUE
);

CREATE TABLE admins_sede (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo TEXT NOT NULL UNIQUE,
    contrasena_hash TEXT NOT NULL,
    sede_id INTEGER NOT NULL REFERENCES sedes(id) ON DELETE CASCADE
);

