def actualizar_financiero(usuario_id, correo, nombre, sede_id, contrasena_hash=None):
    """Cambia los datos del usuario. Si no se da contrasena_hash, la contraseña se conserva."""
    conexion = conectar_central()
    try:
        if contrasena_hash:
            conexion.execute(
                'UPDATE usuarios_financieros SET correo = ?, nombre = ?, sede_id = ?, contrasena_hash = ? WHERE id = ?',
                (correo, nombre, sede_id, contrasena_hash, usuario_id))
        else:
            conexion.execute('UPDATE usuarios_financieros SET correo = ?, nombre = ?, sede_id = ? WHERE id = ?',
                             (correo, nombre, sede_id, usuario_id))
        conexion.commit()
    except Exception:
        conexion.rollback()
        raise
    finally:
        conexion.close()


def cambiar_bloqueo_financiero(usuario_id, bloqueado):
    """Bloquea o desbloquea el acceso. No borra nada: el usuario conserva su historial."""
    conexion = conectar_central()
    try:
        conexion.execute('UPDATE usuarios_financieros SET bloqueado = ? WHERE id = ?',
                         (1 if bloqueado else 0, usuario_id))
        conexion.commit()
    finally:
        conexion.close()


def registrar_acceso_financiero(usuario, accion, detalle=''):
    """Anota en la bitácora central una acción sobre los accesos financieros."""
    conexion = conectar_central()
    try:
        conexion.execute(
            'INSERT INTO auditoria_financieros (fecha, usuario, accion, detalle) VALUES (?, ?, ?, ?)',
            (datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S'), usuario, accion, detalle))
        conexion.commit()
    finally:
        conexion.close()


