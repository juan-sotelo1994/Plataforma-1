"""Sedes: cada sede es un esquema de la base instituto. El esquema "central" guarda la lista de
sedes, los administradores de cada sede, las cuentas de finanzas y la contraseña del superadministrador
(si la cambió).

En la columna "archivo" de la tabla sedes se guarda el nombre del esquema de la sede (por ejemplo
sede_1). Se conserva ese nombre para no cambiar el resto de la aplicación.
"""
import datetime
import uuid

import psycopg
from psycopg import sql

from nucleo.db import (ESQUEMA_CENTRAL, ESQUEMA_CENTRAL_SQL, ESQUEMA_PRINCIPAL, Conexion, crear_base)


# Usuarios del perfil financiero. Viven en el central porque ven todas las sedes.
TABLA_FINANCIEROS_SQL = """CREATE TABLE IF NOT EXISTS usuarios_financieros (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo TEXT NOT NULL UNIQUE,
    nombre TEXT NOT NULL,
    contrasena_hash TEXT NOT NULL,
    creado_en TEXT NOT NULL,
    bloqueado INTEGER NOT NULL DEFAULT 0
)"""
# Las bases que ya tenían la tabla reciben la columna nueva al iniciar
COLUMNA_BLOQUEO_SQL = "ALTER TABLE usuarios_financieros ADD COLUMN IF NOT EXISTS bloqueado INTEGER NOT NULL DEFAULT 0"
# Cada persona del perfil financiero pertenece a una sede y solo ve esa sede
COLUMNA_SEDE_SQL = ("ALTER TABLE usuarios_financieros ADD COLUMN IF NOT EXISTS "
                    "sede_id INTEGER REFERENCES sedes(id)")

# Administradoras financieras: ven las cuentas y las finanzas de todas las sedes (solo lectura).
# Las crea, bloquea y quita el superadministrador, y todo lo que hacen queda en la bitácora.
TABLA_ADMIN_FINANCIERAS_SQL = """CREATE TABLE IF NOT EXISTS administradoras_financieras (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo TEXT NOT NULL UNIQUE,
    nombre TEXT NOT NULL,
    contrasena_hash TEXT NOT NULL,
    creado_en TEXT NOT NULL,
    bloqueado INTEGER NOT NULL DEFAULT 0
)"""

# Bitácora central de accesos del perfil financiero (altas, bajas de acceso, bloqueos)
TABLA_AUDITORIA_FINANCIEROS_SQL = """CREATE TABLE IF NOT EXISTS auditoria_financieros (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TEXT NOT NULL,
    usuario TEXT NOT NULL,
    accion TEXT NOT NULL,
    detalle TEXT
)"""


def conectar_central():
    return Conexion(ESQUEMA_CENTRAL)


def conectar_sede(esquema):
    return Conexion(esquema)


def nombre_nuevo_esquema():
    return f'sede_{uuid.uuid4().hex[:10]}'


def iniciar_central():
    """Crea el esquema central la primera vez (en una base nueva, con una sede principal).

    En las bases que ya existían agrega las tablas nuevas que falten.
    """
    from nucleo.db import _url
    with psycopg.connect(_url()) as pg:
        existe = pg.execute(
            'SELECT 1 FROM information_schema.schemata WHERE schema_name = %s', (ESQUEMA_CENTRAL,)).fetchone()
        if not existe:
            pg.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(ESQUEMA_CENTRAL)))
            pg.execute(sql.SQL('SET search_path TO {}').format(sql.Identifier(ESQUEMA_CENTRAL)))
            with open(ESQUEMA_CENTRAL_SQL, encoding='utf-8') as archivo:
                pg.execute(archivo.read())
            pg.execute("INSERT INTO sedes (nombre, archivo) VALUES ('Sede principal', %s)", (ESQUEMA_PRINCIPAL,))
        pg.execute(sql.SQL('SET search_path TO {}').format(sql.Identifier(ESQUEMA_CENTRAL)))
        pg.execute(TABLA_FINANCIEROS_SQL)
        pg.execute(COLUMNA_BLOQUEO_SQL)
        pg.execute(COLUMNA_SEDE_SQL)
        pg.execute(TABLA_AUDITORIA_FINANCIEROS_SQL)
        pg.execute(TABLA_ADMIN_FINANCIERAS_SQL)
        esquemas = [fila[0] for fila in pg.execute('SELECT archivo FROM sedes').fetchall()]
    if not existe:
        crear_base(ESQUEMA_PRINCIPAL, plantilla=None)
    _agregar_sede_confirmada(esquemas)


def _agregar_sede_confirmada(esquemas):
    """Las sedes que ya existían reciben la columna sede_confirmada (las inscripciones viejas ya tienen sede)."""
    from nucleo.db import _url
    with psycopg.connect(_url()) as pg:
        for esquema in esquemas:
            existe = pg.execute(
                "SELECT 1 FROM information_schema.tables WHERE table_schema = %s AND table_name = 'aspirantes'",
                (esquema,)).fetchone()
            if existe:
                pg.execute(sql.SQL('ALTER TABLE {}.aspirantes ADD COLUMN IF NOT EXISTS '
                                   'sede_confirmada INTEGER NOT NULL DEFAULT 1').format(sql.Identifier(esquema)))


def mover_aspirante(origen, destino, aspirante_id):
    """Traslada la inscripción (con hermanos y documentos) de la base de una sede a la de otra.

    Los requisitos son de cada sede: cada documento pasa al requisito de igual nombre en la sede nueva y
    queda pendiente de revisión allí. Los documentos sin requisito equivalente se descartan.
    Devuelve (id nuevo del aspirante, archivos descartados que se deben borrar del disco).
    Lanza psycopg.IntegrityError si el documento de identidad ya existe en el destino.
    """
    from nucleo.db import _url
    with psycopg.connect(_url()) as pg:
        columnas = [fila[0] for fila in pg.execute(
            "SELECT column_name FROM information_schema.columns WHERE table_schema = %s "
            "AND table_name = 'aspirantes' AND column_name <> 'id' "
            "AND column_name IN (SELECT column_name FROM information_schema.columns "
            "WHERE table_schema = %s AND table_name = 'aspirantes')", (origen, destino)).fetchall()]
        # La jornada y el estudiante son de la sede de origen: no aplican en la nueva
        valores = [sql.SQL('NULL') if c in ('jornada_id', 'estudiante_id') else sql.Identifier(c) for c in columnas]
        nuevo_id = pg.execute(sql.SQL('INSERT INTO {d}.aspirantes ({cols}) SELECT {vals} FROM {o}.aspirantes '
                                      'WHERE id = %s RETURNING id').format(
            d=sql.Identifier(destino), o=sql.Identifier(origen),
            cols=sql.SQL(', ').join(map(sql.Identifier, columnas)), vals=sql.SQL(', ').join(valores)),
            (aspirante_id,)).fetchone()[0]
        pg.execute(sql.SQL('INSERT INTO {d}.hermanos (aspirante_id, nombre, edad, parentesco, orden) '
                           'SELECT %s, nombre, edad, parentesco, orden FROM {o}.hermanos WHERE aspirante_id = %s').format(
            d=sql.Identifier(destino), o=sql.Identifier(origen)), (nuevo_id, aspirante_id))
        pg.execute(sql.SQL(
            'INSERT INTO {d}.documentos_aspirante (aspirante_id, requisito_id, nombre_original, nombre_archivo, subido_en) '
            'SELECT %s, rd.id, doc.nombre_original, doc.nombre_archivo, doc.subido_en '
            'FROM {o}.documentos_aspirante doc JOIN {o}.requisitos ro ON ro.id = doc.requisito_id '
            'JOIN {d}.requisitos rd ON rd.nombre = ro.nombre AND rd.activo = 1 '
            'WHERE doc.aspirante_id = %s').format(d=sql.Identifier(destino), o=sql.Identifier(origen)),
            (nuevo_id, aspirante_id))
        descartados = [fila[0] for fila in pg.execute(sql.SQL(
            'SELECT nombre_archivo FROM {o}.documentos_aspirante WHERE aspirante_id = %s '
            'AND nombre_archivo NOT IN (SELECT nombre_archivo FROM {d}.documentos_aspirante WHERE aspirante_id = %s)'
        ).format(d=sql.Identifier(destino), o=sql.Identifier(origen)), (aspirante_id, nuevo_id)).fetchall()]
        pg.execute(sql.SQL('DELETE FROM {o}.aspirantes WHERE id = %s').format(o=sql.Identifier(origen)),
                   (aspirante_id,))
    return nuevo_id, descartados


def listar_sedes():
    conexion = conectar_central()
    try:
        return conexion.execute('SELECT id, nombre, archivo FROM sedes ORDER BY id').fetchall()
    finally:
        conexion.close()


def listar_financieros():
    conexion = conectar_central()
    try:
        return conexion.execute(
            'SELECT u.id, u.correo, u.nombre, u.creado_en, u.bloqueado, s.nombre AS sede '
            'FROM usuarios_financieros u LEFT JOIN sedes s ON s.id = u.sede_id ORDER BY u.nombre, u.correo'
        ).fetchall()
    finally:
        conexion.close()


def buscar_financiero(correo):
    conexion = conectar_central()
    try:
        return conexion.execute(
            'SELECT u.id, u.correo, u.nombre, u.contrasena_hash, u.bloqueado, u.sede_id, '
            's.archivo AS sede_archivo, s.nombre AS sede_nombre '
            'FROM usuarios_financieros u LEFT JOIN sedes s ON s.id = u.sede_id WHERE u.correo = ?',
            (correo,)).fetchone()
    finally:
        conexion.close()


