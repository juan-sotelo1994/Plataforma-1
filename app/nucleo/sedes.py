def correo_en_uso(correo):
    """True si el correo ya tiene cuenta o inscripción en alguna sede, o es de un administrador o financiero."""
    correo = correo.strip().lower()
    central = conectar_central()
    try:
        if central.execute('SELECT 1 FROM admins_sede WHERE correo = ?', (correo,)).fetchone():
            return True
        if central.execute('SELECT 1 FROM usuarios_financieros WHERE correo = ?', (correo,)).fetchone():
            return True
        if central.execute('SELECT 1 FROM administradoras_financieras WHERE correo = ?', (correo,)).fetchone():
            return True
    finally:
        central.close()
    for sede in listar_sedes():
        conexion = conectar_sede(sede['archivo'])
        try:
            if conexion.execute(
                    'SELECT 1 FROM usuarios WHERE correo = ? UNION SELECT 1 FROM aspirantes WHERE correo = ?',
                    (correo, correo)).fetchone():
                return True
        finally:
            conexion.close()
    return False
