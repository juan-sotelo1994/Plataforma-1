"""Finanzas de cada sede, separadas de lo académico.

Cada sede guarda en su propio esquema: cuentas de ingreso y de egreso, movimientos (los anulados
quedan a la vista), kárdex de artículos con costo promedio y bajas. Cada acción queda en la
auditoría de la sede, y el superadministrador puede verla desde Finanzas.
"""
import datetime
from decimal import Decimal, InvalidOperation

from nucleo.auditoria import registrar
from nucleo.db import IntegrityError


ESQUEMA_FINANZAS = [
    """CREATE TABLE IF NOT EXISTS fin_cuentas (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        tipo TEXT NOT NULL CHECK (tipo IN ('ingreso', 'egreso')),
        nombre TEXT NOT NULL,
        activa INTEGER NOT NULL DEFAULT 1,
        creado_en TEXT NOT NULL,
        UNIQUE (tipo, nombre)
    )""",
    """CREATE TABLE IF NOT EXISTS fin_movimientos (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        fecha TEXT NOT NULL,
        tipo TEXT NOT NULL CHECK (tipo IN ('ingreso', 'egreso')),
        cuenta_id INTEGER NOT NULL REFERENCES fin_cuentas(id),
        monto NUMERIC(16, 2) NOT NULL CHECK (monto > 0),
        concepto TEXT NOT NULL,
        referencia TEXT,
        registrado_por TEXT NOT NULL,
        creado_en TEXT NOT NULL,
        anulado INTEGER NOT NULL DEFAULT 0,
        anulado_por TEXT,
        anulado_en TEXT,
        motivo_anulacion TEXT
    )""",
    """CREATE TABLE IF NOT EXISTS fin_articulos (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        codigo TEXT NOT NULL UNIQUE,
        nombre TEXT NOT NULL,
        unidad TEXT NOT NULL,
        creado_en TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS fin_kardex (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        articulo_id INTEGER NOT NULL REFERENCES fin_articulos(id),
        fecha TEXT NOT NULL,
        tipo TEXT NOT NULL CHECK (tipo IN ('entrada', 'salida', 'baja')),
        cantidad NUMERIC(14, 3) NOT NULL CHECK (cantidad > 0),
        costo_unitario NUMERIC(16, 4) NOT NULL,
        costo_total NUMERIC(16, 2) NOT NULL,
        saldo_cantidad NUMERIC(14, 3) NOT NULL,
        saldo_costo_unitario NUMERIC(16, 4) NOT NULL,
        saldo_valor NUMERIC(16, 2) NOT NULL,
        detalle TEXT,
        registrado_por TEXT NOT NULL,
        creado_en TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS fin_bajas (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        articulo_id INTEGER NOT NULL REFERENCES fin_articulos(id),
        kardex_id INTEGER NOT NULL REFERENCES fin_kardex(id),
        fecha TEXT NOT NULL,
        cantidad NUMERIC(14, 3) NOT NULL,
        costo_total NUMERIC(16, 2) NOT NULL,
        motivo TEXT NOT NULL,
        registrado_por TEXT NOT NULL,
        creado_en TEXT NOT NULL
    )""",
]

CUENTAS_INICIALES = [
    ('ingreso', 'Pensiones'), ('ingreso', 'Matrículas'), ('ingreso', 'Otros ingresos'),
    ('egreso', 'Servicios públicos'), ('egreso', 'Nómina'), ('egreso', 'Mantenimiento'),
    ('egreso', 'Otros egresos'),
]

CENTAVOS = Decimal('0.01')
COSTO = Decimal('0.0001')
CANTIDAD = Decimal('0.001')


def _ahora():
    return datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')


def asegurar(conexion):
    """Crea las tablas de finanzas si la sede todavía no las tiene, y las cuentas iniciales."""
    for ddl in ESQUEMA_FINANZAS:
        conexion.execute(ddl)
    # Las tablas nuevas pueden recibir id en la misma conexión
    conexion.recargar_tablas()
    if conexion.execute('SELECT COUNT(*) FROM fin_cuentas').fetchone()[0] == 0:
        for tipo, nombre in CUENTAS_INICIALES:
            conexion.execute('INSERT INTO fin_cuentas (tipo, nombre, creado_en) VALUES (?, ?, ?)',
                             (tipo, nombre, _ahora()))
    conexion.commit()


# ---------- Validación y consultas ----------

def _fecha(texto):
    try:
        return datetime.date.fromisoformat((texto or '').strip()).isoformat()
    except ValueError:
        raise ValueError('Escriba una fecha válida.')


def _decimal(texto, campo, cuantizar, minimo=Decimal('0.01')):
    try:
        valor = Decimal((texto or '').strip())
    except InvalidOperation:
        raise ValueError(f'Escriba un valor válido en {campo}.')
    if not valor.is_finite() or valor < minimo:
        raise ValueError(f'{campo.capitalize()} debe ser mayor que cero.')
    return valor.quantize(cuantizar)


def _texto_obligatorio(texto, campo):
    limpio = (texto or '').strip()
    if not limpio:
        raise ValueError(f'Escriba {campo}.')
    return limpio


def resumen(conexion):
    """Ingresos, egresos y saldo de la sede (sin los movimientos anulados)."""
    fila = conexion.execute(
        "SELECT COALESCE(SUM(CASE WHEN tipo = 'ingreso' THEN monto END), 0) AS ingresos, "
        "COALESCE(SUM(CASE WHEN tipo = 'egreso' THEN monto END), 0) AS egresos, "
        "COUNT(*) AS movimientos "
        "FROM fin_movimientos WHERE anulado = 0").fetchone()
    return {'ingresos': fila['ingresos'], 'egresos': fila['egresos'],
            'saldo': fila['ingresos'] - fila['egresos'], 'movimientos': fila['movimientos']}


def cuentas_con_totales(conexion):
    return conexion.execute(
        "SELECT c.id, c.tipo, c.nombre, c.activa, "
        "COALESCE(SUM(m.monto) FILTER (WHERE m.anulado = 0), 0) AS total, "
        "COUNT(m.id) FILTER (WHERE m.anulado = 0) AS movimientos "
        "FROM fin_cuentas c LEFT JOIN fin_movimientos m ON m.cuenta_id = c.id "
        "GROUP BY c.id, c.tipo, c.nombre, c.activa ORDER BY c.tipo, c.nombre").fetchall()


def listar_cuentas(conexion, solo_activas=False):
    return conexion.execute(
        'SELECT id, tipo, nombre, activa FROM fin_cuentas WHERE (CAST(? AS INTEGER) = 0 OR activa = 1) '
        'ORDER BY tipo, nombre', (1 if solo_activas else 0,)).fetchall()


def listar_movimientos(conexion, tipo='', cuenta_id='', desde='', hasta='', incluir_anulados=False, limite=500):
    return conexion.execute(
        "SELECT m.id, m.fecha, m.tipo, c.nombre AS cuenta, m.concepto, m.referencia, m.monto, "
        "m.registrado_por, m.creado_en, m.anulado, m.anulado_por, m.motivo_anulacion "
        "FROM fin_movimientos m JOIN fin_cuentas c ON c.id = m.cuenta_id "
        "WHERE (? = '' OR m.tipo = ?) "
        "AND (? = '' OR m.cuenta_id::text = ?) "
        "AND (? = '' OR m.fecha >= ?) AND (? = '' OR m.fecha <= ?) "
        "AND (CAST(? AS INTEGER) = 1 OR m.anulado = 0) "
        "ORDER BY m.fecha DESC, m.id DESC LIMIT ?",
        (tipo, tipo, str(cuenta_id), str(cuenta_id), desde, desde, hasta, hasta,
         1 if incluir_anulados else 0, limite)).fetchall()


def listar_articulos(conexion):
    return conexion.execute(
        "SELECT a.id, a.codigo, a.nombre, a.unidad, "
        "COALESCE((SELECT k.saldo_cantidad FROM fin_kardex k WHERE k.articulo_id = a.id "
        "ORDER BY k.id DESC LIMIT 1), 0) AS existencia, "
        "COALESCE((SELECT k.saldo_valor FROM fin_kardex k WHERE k.articulo_id = a.id "
        "ORDER BY k.id DESC LIMIT 1), 0) AS valor "
        "FROM fin_articulos a ORDER BY a.nombre").fetchall()


def kardex_articulo(conexion, articulo_id):
    return conexion.execute(
        "SELECT id, fecha, tipo, cantidad, costo_unitario, costo_total, saldo_cantidad, "
        "saldo_costo_unitario, saldo_valor, detalle, registrado_por "
        "FROM fin_kardex WHERE articulo_id = ? ORDER BY id", (articulo_id,)).fetchall()


def listar_bajas(conexion, limite=300):
    return conexion.execute(
        "SELECT b.id, b.fecha, a.codigo, a.nombre, b.cantidad, b.costo_total, b.motivo, b.registrado_por, b.creado_en "
        "FROM fin_bajas b JOIN fin_articulos a ON a.id = b.articulo_id "
        "ORDER BY b.id DESC LIMIT ?", (limite,)).fetchall()


# ---------- Cuentas ----------

def crear_cuenta(conexion, tipo, nombre, usuario):
    if tipo not in ('ingreso', 'egreso'):
        raise ValueError('Seleccione si la cuenta es de ingreso o de egreso.')
    nombre = _texto_obligatorio(nombre, 'el nombre de la cuenta')
    try:
        conexion.execute('INSERT INTO fin_cuentas (tipo, nombre, creado_en) VALUES (?, ?, ?)',
                         (tipo, nombre, _ahora()))
    except IntegrityError:
        raise ValueError(f'Ya existe la cuenta «{nombre}» en {tipo}s.')
    registrar(conexion, 'fin_cuenta', f'Creó la cuenta de {tipo} «{nombre}»', usuario=usuario)


def cambiar_estado_cuenta(conexion, cuenta_id, usuario):
    cuenta = conexion.execute('SELECT id, tipo, nombre, activa FROM fin_cuentas WHERE id = ?', (cuenta_id,)).fetchone()
    if cuenta is None:
        raise ValueError('La cuenta no existe.')
    nuevo = 0 if cuenta['activa'] else 1
    conexion.execute('UPDATE fin_cuentas SET activa = ? WHERE id = ?', (nuevo, cuenta_id))
    accion = 'Activó' if nuevo else 'Desactivó'
    registrar(conexion, 'fin_cuenta', f'{accion} la cuenta de {cuenta["tipo"]} «{cuenta["nombre"]}»', usuario=usuario)


# ---------- Movimientos ----------

def registrar_movimiento(conexion, fecha, tipo, cuenta_id, monto, concepto, referencia, usuario):
    fecha = _fecha(fecha)
    monto = _decimal(monto, 'el monto', CENTAVOS)
    concepto = _texto_obligatorio(concepto, 'el concepto')
    if tipo not in ('ingreso', 'egreso'):
        raise ValueError('Seleccione si es un ingreso o un egreso.')
    cuenta = None
    if str(cuenta_id).isdigit():
        cuenta = conexion.execute('SELECT id, tipo, nombre, activa FROM fin_cuentas WHERE id = ?',
                                  (int(cuenta_id),)).fetchone()
    if cuenta is None:
        raise ValueError('Seleccione la cuenta.')
    if cuenta['tipo'] != tipo:
        raise ValueError(f'La cuenta «{cuenta["nombre"]}» es de {cuenta["tipo"]}.')
    if not cuenta['activa']:
        raise ValueError(f'La cuenta «{cuenta["nombre"]}» está desactivada.')
    conexion.execute(
        'INSERT INTO fin_movimientos (fecha, tipo, cuenta_id, monto, concepto, referencia, registrado_por, creado_en) '
        'VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
        (fecha, tipo, cuenta['id'], monto, concepto, (referencia or '').strip() or None, usuario, _ahora()))
    registrar(conexion, 'fin_movimiento',
              f'{tipo.capitalize()} de {monto:,.2f} en «{cuenta["nombre"]}»: {concepto}', usuario=usuario)


def anular_movimiento(conexion, movimiento_id, motivo, usuario):
    """Anula un movimiento: queda registrado y deja de sumar en los saldos."""
    motivo = _texto_obligatorio(motivo, 'el motivo de la anulación')
    fila = conexion.execute('SELECT id, anulado, monto, concepto FROM fin_movimientos WHERE id = ?',
                            (movimiento_id,)).fetchone()
    if fila is None:
        raise ValueError('El movimiento no existe.')
    if fila['anulado']:
        raise ValueError('Ese movimiento ya estaba anulado.')
    conexion.execute(
        'UPDATE fin_movimientos SET anulado = 1, anulado_por = ?, anulado_en = ?, motivo_anulacion = ? WHERE id = ?',
        (usuario, _ahora(), motivo, movimiento_id))
    registrar(conexion, 'fin_movimiento_anulado',
              f'Anuló el movimiento {movimiento_id} de {fila["monto"]:,.2f} ({fila["concepto"]}): {motivo}',
              usuario=usuario)


# ---------- Kárdex y bajas ----------

def crear_articulo(conexion, codigo, nombre, unidad, usuario):
    codigo = _texto_obligatorio(codigo, 'el código del artículo').upper()
    nombre = _texto_obligatorio(nombre, 'el nombre del artículo')
    unidad = (unidad or '').strip() or 'unidad'
    try:
        conexion.execute('INSERT INTO fin_articulos (codigo, nombre, unidad, creado_en) VALUES (?, ?, ?, ?)',
                         (codigo, nombre, unidad, _ahora()))
    except IntegrityError:
        raise ValueError(f'Ya existe un artículo con el código {codigo}.')
    registrar(conexion, 'fin_articulo', f'Creó el artículo {codigo} «{nombre}»', usuario=usuario)


def _movimiento_kardex(conexion, articulo_id, fecha, tipo, cantidad, costo_unitario, detalle, usuario):
    """Agrega una línea al kárdex con el costo promedio ponderado. Devuelve el id de la línea."""
    anterior = conexion.execute(
        'SELECT saldo_cantidad, saldo_costo_unitario, saldo_valor FROM fin_kardex WHERE articulo_id = ? '
        'ORDER BY id DESC LIMIT 1', (articulo_id,)).fetchone()
    saldo_cantidad = anterior['saldo_cantidad'] if anterior else Decimal(0)
    saldo_valor = anterior['saldo_valor'] if anterior else Decimal(0)

    if tipo == 'entrada':
        costo_u = costo_unitario
        costo_total = (cantidad * costo_u).quantize(CENTAVOS)
        nueva_cantidad = saldo_cantidad + cantidad
        nuevo_valor = saldo_valor + costo_total
    else:
        if cantidad > saldo_cantidad:
            raise ValueError(f'Solo hay {saldo_cantidad:g} en existencia; no se puede dar de baja {cantidad:g}.')
        costo_u = anterior['saldo_costo_unitario']
        # Al sacar todo el stock, la línea lleva todo el valor que quedaba (sin centavos sueltos)
        costo_total = saldo_valor if cantidad == saldo_cantidad else (cantidad * costo_u).quantize(CENTAVOS)
        nueva_cantidad = saldo_cantidad - cantidad
        nuevo_valor = saldo_valor - costo_total

    nuevo_costo_u = (nuevo_valor / nueva_cantidad).quantize(COSTO) if nueva_cantidad else Decimal(0)
    cursor = conexion.execute(
        'INSERT INTO fin_kardex (articulo_id, fecha, tipo, cantidad, costo_unitario, costo_total, saldo_cantidad, '
        'saldo_costo_unitario, saldo_valor, detalle, registrado_por, creado_en) '
        'VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)',
        (articulo_id, fecha, tipo, cantidad, costo_u.quantize(COSTO), costo_total, nueva_cantidad, nuevo_costo_u,
         nuevo_valor, detalle, usuario, _ahora()))
    return cursor.lastrowid


def _articulo(conexion, articulo_id):
    articulo = None
    if str(articulo_id).isdigit():
        articulo = conexion.execute('SELECT id, codigo, nombre FROM fin_articulos WHERE id = ?',
                                    (int(articulo_id),)).fetchone()
    if articulo is None:
        raise ValueError('Seleccione el artículo.')
    return articulo


def registrar_entrada(conexion, articulo_id, fecha, cantidad, costo_unitario, detalle, usuario):
    fecha = _fecha(fecha)
    cantidad = _decimal(cantidad, 'la cantidad', CANTIDAD, minimo=CANTIDAD)
    costo_unitario = _decimal(costo_unitario, 'el costo unitario', COSTO, minimo=Decimal(0))
    articulo = _articulo(conexion, articulo_id)
    _movimiento_kardex(conexion, articulo['id'], fecha, 'entrada', cantidad, costo_unitario,
                       (detalle or '').strip() or None, usuario)
    registrar(conexion, 'fin_kardex', f'Entrada de {cantidad:g} de {articulo["codigo"]} «{articulo["nombre"]}»',
              usuario=usuario)


def registrar_baja(conexion, articulo_id, fecha, cantidad, motivo, usuario):
    fecha = _fecha(fecha)
    cantidad = _decimal(cantidad, 'la cantidad', CANTIDAD, minimo=CANTIDAD)
    motivo = _texto_obligatorio(motivo, 'el motivo de la baja')
    articulo = _articulo(conexion, articulo_id)
    kardex_id = _movimiento_kardex(conexion, articulo['id'], fecha, 'baja', cantidad, Decimal(0),
                                   motivo, usuario)
    costo_total = conexion.execute('SELECT costo_total FROM fin_kardex WHERE id = ?', (kardex_id,)).fetchone()[0]
    conexion.execute(
        'INSERT INTO fin_bajas (articulo_id, kardex_id, fecha, cantidad, costo_total, motivo, registrado_por, creado_en) '
        'VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
        (articulo['id'], kardex_id, fecha, cantidad, costo_total, motivo, usuario, _ahora()))
    registrar(conexion, 'fin_baja',
              f'Baja de {cantidad:g} de {articulo["codigo"]} «{articulo["nombre"]}»: {motivo}', usuario=usuario)


# ---------- Vista de solo lectura para el superadministrador ----------

def gastos_operacionales(conexion):
    """Total de egresos por cuenta (gastos operacionales), sin los anulados."""
    return conexion.execute(
        "SELECT c.nombre, COUNT(m.id) AS movimientos, COALESCE(SUM(m.monto), 0) AS total "
        "FROM fin_cuentas c LEFT JOIN fin_movimientos m ON m.cuenta_id = c.id AND m.anulado = 0 "
        "WHERE c.tipo = 'egreso' GROUP BY c.id, c.nombre ORDER BY total DESC, c.nombre").fetchall()


def matricula_financiera(conexion):
    """Recibos de matrícula financiera de la sede y cuántos hay en cada estado."""
    from servicios import matricula_financiera as matricula
    matricula.asegurar(conexion)
    conexion.commit()
    recibos = conexion.execute(
        "SELECT r.id, e.codigo, e.apellidos || ' ' || e.nombres AS estudiante, r.modalidad, r.periodo, "
        "r.fecha_pago, r.estado, r.observacion, r.subido_en "
        "FROM recibos_matricula r JOIN estudiantes e ON e.id = r.estudiante_id "
        "ORDER BY r.subido_en DESC LIMIT 500").fetchall()
    conteos = {estado: 0 for estado in ('pendiente', 'aprobado', 'rechazado')}
    for fila in conexion.execute('SELECT estado, COUNT(*) AS total FROM recibos_matricula GROUP BY estado').fetchall():
        conteos[fila['estado']] = fila['total']
    return recibos, conteos


SECCIONES_SEDE = {
    'resumen': 'Resumen',
    'ingresos': 'Ingresos',
    'egresos': 'Egresos',
    'gastos': 'Gastos operacionales',
    'bajas': 'Bajas',
    'matricula': 'Matrícula financiera',
}


def datos_vista_sede(conexion, seccion):
    """Datos de una sección de la vista de finanzas de una sede (solo lectura)."""
    asegurar(conexion)
    if seccion == 'resumen':
        return {'resumen': resumen(conexion), 'cuentas': cuentas_con_totales(conexion),
                'matricula_conteos': matricula_financiera(conexion)[1]}
    if seccion == 'ingresos':
        return {'movimientos': listar_movimientos(conexion, tipo='ingreso', incluir_anulados=True, limite=500)}
    if seccion == 'egresos':
        return {'movimientos': listar_movimientos(conexion, tipo='egreso', incluir_anulados=True, limite=500)}
    if seccion == 'gastos':
        return {'gastos': gastos_operacionales(conexion)}
    if seccion == 'bajas':
        return {'bajas': listar_bajas(conexion, limite=500)}
    if seccion == 'matricula':
        recibos, conteos = matricula_financiera(conexion)
        return {'recibos': recibos, 'matricula_conteos': conteos}
    return {}


def indicadores_globales():
    """Cifras de todas las sedes juntas, para las tarjetas de Finanzas."""
    from nucleo.sedes import conectar_sede, listar_sedes
    total = {'sedes': 0, 'ingresos': 0, 'egresos': 0, 'saldo': 0, 'movimientos': 0,
             'anulados': 0, 'bajas': 0, 'pendientes': 0}
    sedes = listar_sedes()
    for sede in sedes:
        conexion = conectar_sede(sede['archivo'])
        try:
            asegurar(conexion)
            resumen_sede = resumen(conexion)
            total['ingresos'] += resumen_sede['ingresos']
            total['egresos'] += resumen_sede['egresos']
            total['movimientos'] += resumen_sede['movimientos']
            total['anulados'] += conexion.execute('SELECT COUNT(*) FROM fin_movimientos WHERE anulado = 1').fetchone()[0]
            total['bajas'] += conexion.execute('SELECT COUNT(*) FROM fin_bajas').fetchone()[0]
            total['pendientes'] += matricula_financiera(conexion)[1]['pendiente']
        finally:
            conexion.close()
    total['sedes'] = len(sedes)
    total['saldo'] = total['ingresos'] - total['egresos']
    return total
